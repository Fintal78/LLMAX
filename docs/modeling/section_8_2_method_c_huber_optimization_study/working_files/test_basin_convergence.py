for d in devices:
    d["base_power_ratio"] = (d["stability_pct"] / 100.0) ** 3

def huber_loss(residual, delta):
    abs_res = np.abs(residual)
    if delta == 0.0:
        return abs_res
    elif abs_res <= delta:
        return 0.5 * (abs_res ** 2)
    else:
        return delta * abs_res - 0.5 * (delta ** 2)

def predict_time(d, eta_low, C0_single, C0_dual, k, p, alpha):
    C_rate = d["P_peak"] / d["E_supply"]
    f_th = (d["base_power_ratio"]) ** alpha
    f_skin = 1.0
    C0_base = C0_dual if d["arch"] == "Dual" else C0_single
    C0_eff = C0_base * f_th * f_skin
    
    if C_rate <= C0_eff:
        F_sys = eta_low
    else:
        denom = 1.0 + k * ((C_rate - C0_eff) ** p)
        F_sys = min(1.0, eta_low / denom)
        
    P_eff = d["P_peak"] * F_sys
    T_pred = (d["E_supply"] / P_eff) * 60.0
    return T_pred

def objective(params, delta):
    eta_low, C0_single, C0_dual, k, p, alpha = params
    total_loss = 0.0
    for d in devices:
        T_pred = predict_time(d, eta_low, C0_single, C0_dual, k, p, alpha)
        res = T_pred - d["T_A"]
        total_loss += huber_loss(res, delta)
    return total_loss / len(devices)

# Compare loss at delta = 20 for Basin A (alpha ~ 1.4) vs Basin B (alpha ~ 3.15)
delta = 20.0

# Test Basin A (alpha constrained around [0.5, 2.0], C0_single constrained around [0.1, 0.8])
bounds_basin_A = [
    (0.85, 1.00),   # eta_low
    (0.10, 0.80),   # C0_single
    (3.00, 8.00),   # C0_dual
    (0.50, 3.00),   # k
    (0.15, 0.50),   # p
    (0.50, 2.00)    # alpha (~1.4)
]

res_A = differential_evolution(objective, bounds=bounds_basin_A, args=(delta,), seed=42, popsize=40, maxiter=1000)
loss_A = res_A.fun
params_A = res_A.x

# Test unconstrained DE with popsize=50 across multiple seeds
seeds = [1, 7, 42, 100, 2024]
print("Running Multi-Seed Optimization at Delta = 20.0...")
for s in seeds:
    bounds_full = [(0.50, 1.00), (0.00, 15.00), (0.00, 15.00), (0.00, 10.00), (0.01, 5.00), (0.10, 5.00)]
    res = differential_evolution(objective, bounds=bounds_full, args=(delta,), seed=s, popsize=40, maxiter=1000)
    eta_low, C0_s, C0_d, k, p, alpha = res.x
    print(f"Seed {s:4d} | Loss: {res.fun:.6f} | eta: {eta_low:.4f} | C0_s: {C0_s:.4f} | C0_d: {C0_d:.4f} | k: {k:.4f} | p: {p:.4f} | alpha: {alpha:.4f}")

